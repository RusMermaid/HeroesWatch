#!/usr/bin/env node
// Convert a catalog to current creature terminology. No database connection.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {isDeepStrictEqual} from 'node:util';

const dbRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tiers = JSON.parse(fs.readFileSync(path.join(dbRoot, 'data/creature-tiers.json')));
const dragonCodes = new Set(['FAERIE_DRAGON', 'RUST_DRAGON', 'CRYSTAL_DRAGON', 'AZURE_DRAGON']);
if (tiers.game !== 'HOMM3' || tiers.field !== 'Tier' || !Array.isArray(tiers.tiers) || tiers.tiers.length !== 4 ||
    new Set(tiers.tiers.map(entry => entry.code)).size !== 4 || tiers.tiers.some(entry =>
      !dragonCodes.has(entry.code) || !Number.isInteger(entry.previous) || !Number.isInteger(entry.value) ||
      entry.previous < 1 || entry.previous > 32767 || entry.value < 1 || entry.value > 32767)) {
  throw new Error('Invalid reviewed dragon Tier configuration');
}
export const h1Speed = Object.freeze({Slow: 1, Medium: 2, Fast: 3});

export function prepareCatalog(source) {
  const result = structuredClone(source);
  for (const table of ['CreatureHOMM1', 'CreatureHOMM2', 'CreatureHOMM3', 'CreatureHOMM4']) {
    if (!Array.isArray(result.tables?.[table])) throw new Error(`Missing ${table} array`);
    result.tables[table] = result.tables[table].map(row => {
      if (Object.hasOwn(row, 'Level') && Object.hasOwn(row, 'Tier')) throw new Error(`${table}/${row._key}: both Level and Tier supplied`);
      return Object.fromEntries(Object.entries(row).map(([key, value]) => [key === 'Level' ? 'Tier' : key, value]));
    });
  }
  for (const row of result.tables.CreatureHOMM1) {
    const value = typeof row.Speed === 'string' && Object.hasOwn(h1Speed, row.Speed) ? h1Speed[row.Speed] : row.Speed;
    if (![1, 2, 3].includes(value)) throw new Error(`Unrecognized H1 speed for ${row._key}`);
    row.Speed = value;
  }
  const game = result.tables.Game.find(row => row.SeriesCode === tiers.game);
  if (!game) throw new Error('Missing HOMM3 identity');
  for (const entry of tiers.tiers) {
    const parents = result.tables.Creature.filter(row => [game._key, game.Game_id].filter(value => value != null).includes(row.Game_id) && row.Code === entry.code);
    if (parents.length !== 1) throw new Error(`Expected one HOMM3 ${entry.code}`);
    const row = result.tables.CreatureHOMM3.find(row => row._key === parents[0]._key || row.Creature_id === parents[0]._key);
    if (!row || ![entry.previous, entry.value].includes(row.Tier)) throw new Error(`Unrecognized prior Tier for ${entry.code}`);
    row.Tier = entry.value;
  }
  return result;
}

export function tierCorrectionSql() {
  const commands = tiers.tiers.map(({code, previous, value}) => `  SELECT d."Tier" INTO previous_tier
  FROM heroes_watch."CreatureHOMM3" d
  JOIN heroes_watch."Creature" c ON c."Creature_id" = d."Creature_id"
  JOIN heroes_watch."Game" g ON g."Game_id" = c."Game_id"
  WHERE g."SeriesCode" = 'HOMM3' AND c."Code" = '${code}';
  IF FOUND THEN
    IF previous_tier IS DISTINCT FROM ${previous} AND previous_tier IS DISTINCT FROM ${value} THEN
      RAISE EXCEPTION 'Unexpected existing Tier for ${code}; no changes applied';
    END IF;
    UPDATE heroes_watch."CreatureHOMM3" d SET "Tier" = ${value}
    FROM heroes_watch."Creature" c, heroes_watch."Game" g
    WHERE d."Creature_id" = c."Creature_id" AND c."Game_id" = g."Game_id"
      AND g."SeriesCode" = 'HOMM3' AND c."Code" = '${code}' AND d."Tier" = ${previous};
  END IF;`).join('\n');
  return `-- Generated by prepare-catalog-v5.mjs from data/creature-tiers.json.
-- Apply after migration 0004 and before importing current content into an older catalog.
-- Existing target tiers are accepted; unexpected values abort the entire transaction.
BEGIN;
SET LOCAL lock_timeout = '15s';
LOCK TABLE heroes_watch."Game", heroes_watch."Creature", heroes_watch."CreatureHOMM3" IN SHARE ROW EXCLUSIVE MODE;
DO $tiers$
DECLARE previous_tier SMALLINT;
BEGIN
${commands}
END
$tiers$;
COMMIT;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const options = {input: path.join(dbRoot, 'data/heroeswatch.json'), output: null, check: false};
  for (let index = 2; index < process.argv.length; index++) {
    const arg = process.argv[index];
    if (arg === '--check') options.check = true;
    else if (arg === '--input' || arg === '--output') {
      const value = process.argv[++index];
      if (!value || value.startsWith('--')) throw new Error(`Missing ${arg} value`);
      options[arg.slice(2)] = path.resolve(value);
    } else throw new Error(`Unknown argument ${arg}`);
  }
  const original = JSON.parse(fs.readFileSync(options.input));
  const current = prepareCatalog(original);
  const sqlPath = path.join(dbRoot, 'data/creature-tier-corrections.sql');
  if (options.check) {
    if (!isDeepStrictEqual(original, current)) throw new Error('Catalog is not using the reviewed Tier and numeric Speed values');
    if (!fs.existsSync(sqlPath) || fs.readFileSync(sqlPath, 'utf8') !== tierCorrectionSql()) throw new Error('Regenerate creature-tier-corrections.sql');
    console.log('Creature Tier, numeric Speed and correction SQL verified.');
  } else {
    if (!options.output) throw new Error('Supply --output explicitly; input is never overwritten by default');
    if (fs.existsSync(options.output) && fs.lstatSync(options.output).isSymbolicLink()) throw new Error('Output must not be a symbolic link');
    fs.mkdirSync(path.dirname(options.output), {recursive: true});
    fs.writeFileSync(options.output, JSON.stringify(current, null, 2) + '\n');
    fs.writeFileSync(sqlPath, tierCorrectionSql());
    console.log('Prepared creature Tier/numeric Speed values and guarded correction SQL. No database connection.');
  }
}
